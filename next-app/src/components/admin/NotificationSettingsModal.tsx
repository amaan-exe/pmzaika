'use client';

import React, { useEffect, useState } from 'react';
import {
  SOUND_PROFILES,
  type SoundConfig,
  type SoundProfile,
} from './audioAlert';

interface NotificationSettingsModalProps {
  isOpen: boolean;
  onClose: () => void;
  config: SoundConfig;
  onUpdateConfig: (updates: Partial<SoundConfig>) => void;
  onTestSound: (profile?: SoundProfile, volume?: number) => void;
}

function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const rawData = window.atob(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

export default function NotificationSettingsModal({
  isOpen,
  onClose,
  config,
  onUpdateConfig,
  onTestSound,
}: NotificationSettingsModalProps) {
  const [pushStatus, setPushStatus] = useState<'checking' | 'active' | 'prompt' | 'denied' | 'unsupported'>('checking');
  const [pushLoading, setPushLoading] = useState(false);
  const [testPushLoading, setTestPushLoading] = useState(false);
  const [feedback, setFeedback] = useState<{ type: 'success' | 'error'; message: string } | null>(null);

  // Check current browser push permission and subscription status
  useEffect(() => {
    if (!isOpen) return;

    if (typeof window === 'undefined' || !('serviceWorker' in navigator) || !('Notification' in window)) {
      setPushStatus('unsupported');
      return;
    }

    if (Notification.permission === 'denied') {
      setPushStatus('denied');
      return;
    }

    if (Notification.permission === 'default') {
      setPushStatus('prompt');
      return;
    }

    navigator.serviceWorker.ready
      .then((reg) => reg.pushManager.getSubscription())
      .then((sub) => {
        setPushStatus(sub ? 'active' : 'prompt');
      })
      .catch(() => {
        setPushStatus('prompt');
      });
  }, [isOpen]);

  if (!isOpen) return null;

  // Subscribe this browser device to Web Push
  const handleEnablePush = async () => {
    setPushLoading(true);
    setFeedback(null);

    try {
      if (!('serviceWorker' in navigator) || !('Notification' in window)) {
        throw new Error('Push notifications are not supported on this browser.');
      }

      const permission = await Notification.requestPermission();
      if (permission !== 'granted') {
        setPushStatus('denied');
        throw new Error('Notification permission was blocked in your browser settings.');
      }

      // Register or get existing service worker registration
      const reg = await navigator.serviceWorker.register('/sw.js');
      await navigator.serviceWorker.ready;

      // Fetch VAPID public key from backend
      const res = await fetch('/api/admin/notifications');
      const data = await res.json();
      if (!data.vapidPublicKey) {
        throw new Error('VAPID public key could not be retrieved from the server.');
      }

      const appServerKey = urlBase64ToUint8Array(data.vapidPublicKey);
      let sub = await reg.pushManager.getSubscription();

      if (!sub) {
        sub = await reg.pushManager.subscribe({
          userVisibleOnly: true,
          applicationServerKey: appServerKey.buffer as ArrayBuffer,
        });
      }

      const subJson = sub.toJSON();
      if (!subJson.endpoint || !subJson.keys?.p256dh || !subJson.keys?.auth) {
        throw new Error('Invalid push subscription format generated by browser.');
      }

      // Register subscription on backend
      const registerRes = await fetch('/api/admin/notifications', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          endpoint: subJson.endpoint,
          keys: {
            p256dh: subJson.keys.p256dh,
            auth: subJson.keys.auth,
          },
        }),
      });

      if (!registerRes.ok) {
        throw new Error('Failed to save push subscription on the server.');
      }

      setPushStatus('active');
      setFeedback({
        type: 'success',
        message: '✅ Push notifications enabled! You will receive loud alerts even when the browser is in the background.',
      });
    } catch (err) {
      setFeedback({
        type: 'error',
        message: err instanceof Error ? err.message : 'Could not enable push notifications.',
      });
    } finally {
      setPushLoading(false);
    }
  };

  // Send a real test push notification to this device
  const handleSendTestPush = async () => {
    setTestPushLoading(true);
    setFeedback(null);

    try {
      const res = await fetch('/api/admin/notifications/test', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          channel: 'webpush',
          message: '🚨 PM Zaika Kitchen Alert Test! Orders will ring and vibrate like this.',
        }),
      });

      const result = await res.json();
      if (!res.ok) {
        throw new Error(result.error || 'Test notification failed');
      }

      setFeedback({
        type: 'success',
        message: '🔔 Test push notification sent! Check your notification center.',
      });
    } catch (err) {
      setFeedback({
        type: 'error',
        message: err instanceof Error ? err.message : 'Failed to send test push alert.',
      });
    } finally {
      setTestPushLoading(false);
    }
  };

  return (
    <div className="admin-modal-backdrop" onClick={onClose}>
      <div
        className="admin-modal-card admin-notification-modal"
        onClick={(e) => e.stopPropagation()}
        role="dialog"
        aria-modal="true"
        aria-labelledby="notification-settings-title"
      >
        <div className="admin-modal-header">
          <div className="admin-modal-header-titles">
            <h2 id="notification-settings-title" className="admin-modal-title">
              🔔 Order Notification Settings
            </h2>
            <p className="admin-modal-subtitle">
              Configure audio alarms, repeating chimes, and browser push alerts.
            </p>
          </div>
          <button
            type="button"
            className="admin-modal-close-btn"
            onClick={onClose}
            aria-label="Close settings"
          >
            ✕
          </button>
        </div>

        {feedback && (
          <div
            className={`admin-notification-feedback ${
              feedback.type === 'success' ? 'feedback-success' : 'feedback-error'
            }`}
          >
            {feedback.message}
          </div>
        )}

        <div className="admin-notification-sections">
          {/* Section 1: Audio & Sound Alerts */}
          <section className="admin-notification-section">
            <div className="admin-section-heading">
              <span className="admin-section-icon">🔊</span>
              <div>
                <h3 className="admin-section-title">Kitchen Audio Alarm</h3>
                <p className="admin-section-desc">
                  Loud acoustic chimes played when customer orders land in the queue.
                </p>
              </div>
            </div>

            <div className="admin-notification-grid">
              {/* Sound on/off toggle */}
              <label className="admin-toggle-control">
                <input
                  type="checkbox"
                  checked={config.enabled}
                  onChange={(e) => onUpdateConfig({ enabled: e.target.checked })}
                />
                <span className="admin-toggle-label">
                  <strong>Enable Order Arrival Sound</strong>
                  <small>Play high-volume acoustic chime on every new order</small>
                </span>
              </label>

              {/* Continuous repeating ring toggle */}
              <label className="admin-toggle-control">
                <input
                  type="checkbox"
                  checked={config.repeatUntilAcknowledged}
                  onChange={(e) =>
                    onUpdateConfig({ repeatUntilAcknowledged: e.target.checked })
                  }
                  disabled={!config.enabled}
                />
                <span className="admin-toggle-label">
                  <strong>Continuous Alarm Mode (Zomato / Swiggy Style)</strong>
                  <small>
                    Keep ringing every 2.8 seconds until staff accepts or silences the alert
                  </small>
                </span>
              </label>

              {/* Sound Profile Selector */}
              <div className="admin-field-group">
                <label className="admin-form-label">Select Alert Tone</label>
                <div className="admin-sound-profile-list">
                  {SOUND_PROFILES.map((profile) => (
                    <button
                      key={profile.id}
                      type="button"
                      className={`admin-sound-profile-card ${
                        config.profile === profile.id ? 'active' : ''
                      }`}
                      onClick={() => {
                        onUpdateConfig({ profile: profile.id });
                        onTestSound(profile.id, config.volume);
                      }}
                      disabled={!config.enabled}
                    >
                      <span className="profile-icon">{profile.icon}</span>
                      <div className="profile-details">
                        <strong className="profile-name">{profile.name}</strong>
                        <span className="profile-desc">{profile.description}</span>
                      </div>
                      {config.profile === profile.id && (
                        <span className="profile-active-tag">Active</span>
                      )}
                    </button>
                  ))}
                </div>
              </div>

              {/* Volume Slider & Test Button */}
              <div className="admin-volume-row">
                <div className="admin-volume-control">
                  <label className="admin-form-label" htmlFor="sound-volume-slider">
                    Alarm Volume: {Math.round(config.volume * 100)}%
                  </label>
                  <input
                    id="sound-volume-slider"
                    type="range"
                    min="20"
                    max="100"
                    step="5"
                    value={Math.round(config.volume * 100)}
                    onChange={(e) =>
                      onUpdateConfig({ volume: Number(e.target.value) / 100 })
                    }
                    disabled={!config.enabled}
                    className="admin-slider"
                  />
                </div>

                <button
                  type="button"
                  className="admin-btn admin-btn--secondary"
                  onClick={() => onTestSound()}
                  title="Test selected tone through speakers"
                >
                  <span>▶️ Test Sound</span>
                </button>
              </div>
            </div>
          </section>

          {/* Section 2: Browser Web Push Notifications */}
          <section className="admin-notification-section">
            <div className="admin-section-heading">
              <span className="admin-section-icon">📲</span>
              <div>
                <h3 className="admin-section-title">Browser Web Push Notifications</h3>
                <p className="admin-section-desc">
                  High-priority alerts with persistent vibration, active even when the tab is hidden.
                </p>
              </div>
            </div>

            <div className="admin-push-card">
              <div className="admin-push-status-row">
                <span className="admin-push-status-label">Device Status:</span>
                <span className={`admin-push-badge status-${pushStatus}`}>
                  {pushStatus === 'active' && '🟢 Push Alerts Active'}
                  {pushStatus === 'prompt' && '🟡 Needs Permission'}
                  {pushStatus === 'denied' && '🔴 Blocked in Browser'}
                  {pushStatus === 'unsupported' && '⚪ Unsupported'}
                  {pushStatus === 'checking' && '⏳ Checking…'}
                </span>
              </div>

              <p className="admin-push-info-text">
                When enabled, incoming orders trigger a loud multi-stage vibration and persistent lockscreen
                notification on this device with quick action buttons.
              </p>

              <div className="admin-push-buttons">
                {pushStatus !== 'active' ? (
                  <button
                    type="button"
                    className="admin-btn admin-btn--primary"
                    onClick={handleEnablePush}
                    disabled={pushLoading || pushStatus === 'denied' || pushStatus === 'unsupported'}
                  >
                    <span>
                      {pushLoading ? 'Setting up…' : '📲 Enable Push Notifications on this Device'}
                    </span>
                  </button>
                ) : (
                  <button
                    type="button"
                    className="admin-btn admin-btn--secondary"
                    onClick={handleSendTestPush}
                    disabled={testPushLoading}
                  >
                    <span>
                      {testPushLoading ? 'Sending…' : '🔔 Send Test Push Alert'}
                    </span>
                  </button>
                )}
              </div>
            </div>
          </section>
        </div>

        <div className="admin-modal-footer">
          <button type="button" className="admin-btn admin-btn--primary" onClick={onClose}>
            Done
          </button>
        </div>
      </div>
    </div>
  );
}
